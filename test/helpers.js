const crypto = require("crypto");
const fs = require("fs");
const os = require("os");
const path = require("path");
const { execFileSync } = require("child_process");

// DB-backed tests truncate tables, so they only ever run against a local database.
function testDatabaseUrl() {
  const url = process.env.TEST_DATABASE_URL;
  if (!url) return null;
  const host = new URL(url).hostname;
  if (host !== "localhost" && host !== "127.0.0.1") {
    throw new Error(`TEST_DATABASE_URL must point at localhost, got ${host}`);
  }
  return url;
}

const SKIP_DB = testDatabaseUrl() ? false : "set TEST_DATABASE_URL to a local Postgres to run";

function sign(body, secret) {
  return "sha256=" + crypto.createHmac("sha256", secret).update(body).digest("hex");
}

// Puts test/bin/yt-dlp ahead of the real one for this process and anything it spawns.
const STUB_BIN = path.join(__dirname, "bin");
const PATH_WITH_STUBS = `${STUB_BIN}${path.delimiter}${process.env.PATH}`;

function tempDir() {
  return fs.mkdtempSync(path.join(os.tmpdir(), "due-test-"));
}

// A 4-second 360x640 clip generated by ffmpeg, with or without a tone on the audio track.
function makeVideo(dir, { audio = true } = {}) {
  const file = path.join(dir, audio ? "clip.mp4" : "silent.mp4");
  const inputs = ["-f", "lavfi", "-i", "testsrc=duration=4:size=360x640:rate=10"];
  if (audio) inputs.push("-f", "lavfi", "-i", "sine=duration=4");
  execFileSync("ffmpeg", ["-v", "error", "-y", ...inputs, "-shortest", "-pix_fmt", "yuv420p", file]);
  return file;
}

module.exports = { testDatabaseUrl, SKIP_DB, sign, PATH_WITH_STUBS, tempDir, makeVideo };
